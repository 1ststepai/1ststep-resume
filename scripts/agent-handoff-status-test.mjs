#!/usr/bin/env node
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

function read(rel) {
  return readFileSync(join(root, rel), 'utf8');
}

const agents = read('AGENTS.md');
const currentState = read('docs/agents/CURRENT-STATE.md');
const nextActions = read('docs/agents/NEXT-ACTIONS.md');
const decisions = read('docs/agents/DECISIONS.md');
const handoff = read('docs/agents/HANDOFF.md');
const readme = read('docs/agents/README.md');

for (const section of [
  '## Cross-agent handoff',
  '## Working-tree safety',
  '## Branch and worktree rules',
  '## Commit rules',
  '## Release rules',
  '## Prohibited shortcuts',
  'docs/agents/HANDOFF.md',
  'docs/status.md',
]) {
  assert.match(agents, new RegExp(section.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')));
}

const handoffFields = [
  'ACTIVE AGENT:',
  'LAST AGENT:',
  'TIMESTAMP:',
  'REPOSITORY:',
  'CANONICAL BRANCH:',
  'HEAD SHA:',
  'ACTIVE BRANCH:',
  'ACTIVE WORKTREE:',
  'TASK ID:',
  'TASK:',
  'STATUS:',
  'LAST COMPLETED ACTION:',
  'FILES CHANGED:',
  'COMMITS CREATED:',
  'UNCOMMITTED CHANGES:',
  'TESTS RUN:',
  'TEST RESULTS:',
  'KNOWN FAILURES:',
  'BLOCKERS:',
  'DO NOT CHANGE:',
  'NEXT ACTION:',
  'NEXT VERIFICATION:',
  'DEPLOYMENT STATUS:',
];
for (const field of handoffFields) {
  assert.match(handoff, new RegExp(`^${field}`, 'm'));
}

assert.match(handoff, /<!-- git-state:start -->/);
assert.match(handoff, /<!-- git-state:end -->/);
assert.match(currentState, /<!-- git-state:start -->/);
assert.match(currentState, /<!-- git-state:end -->/);

assert.match(currentState, /8d3ac083e4906c7d2940e7e4501191b8f4c923d3/);
assert.match(currentState, /cursor\/job-agent-ui-ux-polish-20260917/);
assert.match(currentState, /7ed4e183d445baf2d1129b90e38fcffe3cfec59a/);
assert.match(currentState, /NOT HOSTED VERIFIED/);
assert.match(currentState, /IMPLEMENTED/);
assert.match(currentState, /COMMITTED/);
assert.match(currentState, /PUSHED/);
assert.match(currentState, /MERGED/);
assert.match(currentState, /DEPLOYED/);
assert.match(currentState, /HOSTED VERIFIED/);
assert.doesNotMatch(currentState, /\bStatus:\s*done\b/i);
assert.doesNotMatch(currentState, /\bthis (is|candidate is) done\b/i);

assert.match(nextActions, /P0-2/);
assert.match(nextActions, /8d3ac083e4906c7d2940e7e4501191b8f4c923d3/);
assert.match(nextActions, /npm run pretest:concierge/);
const nextActionHeadings = [...nextActions.matchAll(/^### (P\d+-\d+) — (.+)$/gm)].map((match) => match[2]);
assert.ok(nextActionHeadings.length >= 2, 'NEXT-ACTIONS.md needs executable P0 items');
for (const title of nextActionHeadings) {
  assert.doesNotMatch(title, /^continue implementation\.?$/i);
}

assert.match(decisions, /D-2026-09-17-ux-presentation-only/);
assert.match(decisions, /JOB_AGENT_OWNER_REVIEWED_POLICY/);
assert.match(decisions, /bbb6ee3/);

assert.match(readme, /Chat history is not/);
assert.match(agents, /Never silently overwrite another agent's uncommitted work/);

const nextActionBlock = handoff.match(/^NEXT ACTION:\s*(.+)$/m);
assert.ok(nextActionBlock, 'HANDOFF.md must have NEXT ACTION');
assert.doesNotMatch(nextActionBlock[1], /^continue implementation\.?$/i);
assert.match(nextActionBlock[1], /8d3ac08|agent:handoff-status|pretest:concierge|Commit the handoff/i);

const script = read('scripts/agent-handoff-status.mjs');
assert.match(script, /Never writes/);
assert.doesNotMatch(script, /writeFileSync\(protectedPaths/);
assert.match(script, /DECISIONS\.md/);
assert.match(script, /NEXT-ACTIONS\.md/);

const gitState = read('docs/agents/GIT-STATE.md');
assert.match(gitState, /GIT-STATE \(generated\)/);
assert.match(gitState, /HEAD SHA:/);
assert.match(gitState, /Do not edit this file by hand/);

assert.match(handoff, /HEAD SHA: `[0-9a-f]{40}`/);
assert.match(handoff, /TASK ID: UX-POLISH-20260917/);
assert.match(handoff, /DO NOT CHANGE: auth, consent/);

execFileSync(process.execPath, [join(root, 'scripts/agent-handoff-status.mjs'), '--check'], {
  cwd: root,
  stdio: 'pipe',
});

console.log('agent-handoff-status: protocol files, protected writes, and cold-start fields PASS.');
