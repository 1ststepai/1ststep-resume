import assert from 'node:assert/strict';
import './applicant-vault-error-test.mjs';
import { grantVaultConsent, revokeVaultFact } from '../lib/applicant-vault-domain.js';
import { matchingAnswerMemory, rememberApplicationAnswer, resolveApplicationAnswer, forgetAnswerMemory, reuseApplicationAnswers } from '../lib/application-answer-memory.js';
import { applicationSessionPolicyLevel, validateApplicationSessionMutationBody } from '../api/application-sessions.js';
const session = { id:'application_test_1', state:'Waiting for You', stage:'employer_form', role:{employer:'Example Employer'}, actions:[{id:'action_test_1',type:'AMBIGUOUS_FACT',status:'open',metadata:{question:'Describe your vendor warranty experience.'}}], timeline:[], approvals:{} };
const input = {actionId:'action_test_1',statement:'I handled equipment warranty claims and terms and conditions with vendors at Example Company.'};
const blank = grantVaultConsent();
const vault = rememberApplicationAnswer(blank,session,input);
const fact = vault.facts[0];
assert.equal(fact.versions[0].value,input.statement);
assert.equal(fact.versions[0].scope.exactStatement,input.statement);
assert.equal(matchingAnswerMemory(vault,{question:session.actions[0].metadata.question,applicationId:'other',employer:'Elsewhere'}).id,fact.id);
assert.equal(matchingAnswerMemory(vault,{question:'Did you own RMA adjudication?',applicationId:session.id,employer:session.role.employer}),null);
assert.throws(()=>rememberApplicationAnswer(vault,session,{...input,statement:'I have no vendor experience.'}),/differs/);
const corrected = rememberApplicationAnswer(vault,session,{...input,statement:'I assisted with equipment warranty claims only.',replaceVersion:1});
assert.throws(()=>resolveApplicationAnswer(session,corrected,{actionId:input.actionId,factId:fact.id,factVersion:1,confirmed:true}),/current/);
const forgotten = revokeVaultFact(vault,fact.id);
assert.equal(matchingAnswerMemory(forgotten,{question:session.actions[0].metadata.question,applicationId:session.id,employer:session.role.employer}),null);
const scoped = rememberApplicationAnswer(blank,session,{...input,scope:'employer'});
assert.equal(matchingAnswerMemory(scoped,{question:session.actions[0].metadata.question,applicationId:'other',employer:'Other Employer'}),null);
const exception = rememberApplicationAnswer(blank,session,{...input,statement:'I approve this exception only for this application.'});
assert.equal(exception.facts[0].versions[0].scope.kind,'application');
assert.equal(exception.facts[0].versions[0].autoReuse,false);
assert.throws(()=>rememberApplicationAnswer(blank,session,{...input,statement:'Maybe I handled warranties.'}),/certain/);
assert.throws(()=>rememberApplicationAnswer(blank,session,{...input,statement:'My password is example.'}),/not allowed/);
assert.throws(()=>rememberApplicationAnswer(blank,session,{...input,statement:'123456'}),/not allowed/);
assert.throws(()=>rememberApplicationAnswer(blank,session,{...input,statement:'I have security clearance.'}),/opt-in/);
const resolved = resolveApplicationAnswer(session,vault,{actionId:input.actionId,factId:fact.id,factVersion:1,confirmed:true});
assert.equal(resolved.state,'Preparing');
assert.equal(resolved.actions[0].status,'resolved');
assert.deepEqual(resolved.approvals,session.approvals);
assert.equal(JSON.stringify(resolved).includes(input.statement),false);
assert.equal(resolved.submissionAttempt,undefined);
assert.throws(()=>resolveApplicationAnswer({...session,state:'Paused'},vault,{actionId:input.actionId,factId:fact.id,factVersion:1,confirmed:true}),/unpaused/);
assert.equal(applicationSessionPolicyLevel({action:'resolve-remembered-answer'}),'AUTHORIZATION');
assert.throws(()=>validateApplicationSessionMutationBody({action:'resolve-remembered-answer',statement:'not allowed'}),/references/);
assert.equal(JSON.stringify(forgetAnswerMemory(vault,fact.id)).includes(input.statement),false);
const expired = rememberApplicationAnswer(blank,session,{...input,expiresAt:'2030-01-01'},new Date('2029-01-01'));
assert.equal(matchingAnswerMemory(expired,{question:session.actions[0].metadata.question,now:Date.parse('2031-01-01')}),null);
console.log('Application memory safety assertions passed. No external calls.');

const futureSession = { ...session, id: 'future_application', role: { employer: 'Another Employer' } };
const reused = reuseApplicationAnswers(futureSession, vault);
assert.equal(reused.actions[0].status, 'resolved');
assert.equal(reused.actions[0].metadata.answerReference.factVersion, 1);
assert.equal(JSON.stringify(reused).includes(input.statement), false);
assert.deepEqual(reused.approvals, futureSession.approvals);
assert.equal(reuseApplicationAnswers(reused, vault), reused);
assert.equal(reuseApplicationAnswers(futureSession, forgotten), futureSession);
assert.equal(reuseApplicationAnswers(futureSession, scoped), futureSession);
assert.equal(reuseApplicationAnswers(futureSession, expired, new Date('2031-01-01')), futureSession);
assert.equal(reuseApplicationAnswers(futureSession, { ...vault, consent: { status: 'revoked' } }), futureSession);
const paused = { ...futureSession, state: 'Paused' };
assert.equal(reuseApplicationAnswers(paused, vault), paused);
const attempted = { ...futureSession, submissionAttempt: { status: 'unknown' } };
assert.equal(reuseApplicationAnswers(attempted, vault), attempted);
const manual = { ...vault, facts: vault.facts.map(f => ({ ...f, versions: f.versions.map(v => ({ ...v, autoReuse: false })) })) };
assert.equal(reuseApplicationAnswers(futureSession, manual), futureSession);
assert.equal(reuseApplicationAnswers(futureSession, corrected).actions[0].metadata.answerReference.factVersion, 2);
assert.equal(applicationSessionPolicyLevel({ action: 'prepare-employer-step' }), 'AUTHORIZATION');
console.log('Automatic answer reuse respects current versions, scopes, revocation, pause, and authorization.');
